
# Import datetime to represent the date and time of a prediction record.
from datetime import datetime

# Import Pydantic components for data validation and configuration.
from pydantic import BaseModel, Field, ConfigDict


# ============================================================
# 1. PREDICTION INPUT SCHEMA
# ============================================================
# This schema validates the patient data submitted to the
# diabetes prediction API.
#
# BaseModel provides Pydantic's data validation functionality.
# Field() defines additional validation rules for each field.


class PredictionInput(BaseModel):

    # Number of pregnancies must be zero or greater.
    pregnancies: int = Field(ge=0)

    # Glucose must be greater than zero.
    # NaN and infinity values are not allowed.
    glucose: float = Field(gt=0, allow_inf_nan=False)

    # Blood pressure must be greater than zero.
    blood_pressure: float = Field(gt=0, allow_inf_nan=False)

    # Skin thickness must be greater than zero.
    skin_thickness: float = Field(gt=0, allow_inf_nan=False)

    # Insulin must be greater than zero.
    insulin: float = Field(gt=0, allow_inf_nan=False)

    # BMI must be greater than zero.
    bmi: float = Field(gt=0, allow_inf_nan=False)

    # Diabetes pedigree function must be zero or greater.
    diabetes_pedigree_function: float = Field(
        ge=0,
        allow_inf_nan=False
    )

    # Age must be greater than zero.
    age: int = Field(gt=0)

# ============================================================
# 2. SHAP EXPLANATION RESPONSE SCHEMA
# ============================================================

class PredictionExplanationResponse(BaseModel):

    # Baseline model output calculated by SHAP.
    base_value: float

    # Model decision score after adding all SHAP contributions.
    model_output: float

    # Individual SHAP contribution for each patient feature.
    feature_contributions: dict[str, float]



# ============================================================
# 3. PREDICTION RESPONSE SCHEMA
# ============================================================
# This schema defines the response returned immediately
# after the ML model generates a prediction.
#
# It contains the predicted class and probabilities.


class PredictionResponse(BaseModel):

    # Predicted class: 0 or 1.
    predicted_class: int

    # Model probability for class 0.
    probability_class_0: float

    # Model probability for class 1.
    probability_class_1: float

    # Probability corresponding to the predicted class.
    predicted_class_probability: float

    # SHAP explanation for this prediction.
    explanation: PredictionExplanationResponse


# ============================================================
# 4. PREDICTION HISTORY RESPONSE SCHEMA
# ============================================================
# This schema defines the structure of historical prediction
# records retrieved from the MySQL predictions table.
#
# It allows Pydantic to read values directly from SQLAlchemy
# model objects.


class PredictionHistoryResponse(BaseModel):

    # Enables validation from object attributes.
    # This is useful when returning SQLAlchemy database records.
    model_config = ConfigDict(from_attributes=True)

    # Unique ID of the prediction record.
    id: int

    # ID of the ML model that generated the prediction.
    model_id: int

    # Patient input features saved in the database.
    pregnancies: int
    glucose: float
    blood_pressure: float
    skin_thickness: float
    insulin: float
    bmi: float
    diabetes_pedigree_function: float
    age: int

    # Prediction generated by the ML model.
    predicted_class: int

    # Probability corresponding to the predicted class.
    predicted_probability: float

    # Date and time when the prediction was saved.
    created_at: datetime

# ============================================================
# 5. PREDICTION DASHBOARD RESPONSE SCHEMA
# ============================================================
# This schema defines the summary statistics returned
# by the prediction dashboard API.


class PredictionDashboardResponse(BaseModel):

    # Total number of predictions generated by the user.
    total_predictions: int = Field(ge=0)

    # Number of predictions classified as class 0.
    class_0_predictions: int = Field(ge=0)

    # Number of predictions classified as class 1.
    class_1_predictions: int = Field(ge=0)

    # Percentage of predictions belonging to class 0.
    class_0_percentage: float = Field(ge=0, le=100)

    # Percentage of predictions belonging to class 1.
    class_1_percentage: float = Field(ge=0, le=100)

    # Date and time of the user's latest prediction.
    # None means the user has not generated any predictions.
    latest_prediction: datetime | None = None

# ============================================================
# 6. GLOBAL SHAP EXPLANATION RESPONSE SCHEMA
# ============================================================
# This schema defines the structure of global SHAP feature
# importance results returned by the explainability API.
#
# It contains the number of analysed records and the average
# absolute SHAP importance of each input feature.


class GlobalSHAPResponse(BaseModel):

    # Total number of dataset records analysed by SHAP.
    total_records_analysed: int = Field(gt=0)

    # Mean absolute SHAP importance for each feature.
    # Dictionary keys represent feature names.
    # Dictionary values represent their importance scores.
    feature_importance: dict[str, float]


# ============================================================
# 7. ADMIN PREDICTION MONITORING RESPONSE SCHEMA
# ============================================================
# This schema defines the prediction information returned
# to administrators through the system-wide monitoring API.
#
# IMPORTANT:
# Patient medical input features are intentionally excluded.
# This prevents unnecessary exposure of sensitive patient data
# when administrators monitor prediction activity.


class AdminPredictionResponse(BaseModel):

    # Enables validation directly from SQLAlchemy model objects.
    model_config = ConfigDict(from_attributes=True)

    # Unique ID of the prediction record.
    id: int

    # ID of the user who generated this prediction.
    user_id: int

    # ID of the ML model associated with this prediction.
    model_id: int

    # Predicted class: 0 (non-diabetic) or 1 (diabetic).
    predicted_class: int = Field(ge=0, le=1)

    # Probability corresponding to the predicted class.
    predicted_probability: float = Field(ge=0, le=1)

    # Date and time when the prediction was generated.
    created_at: datetime
